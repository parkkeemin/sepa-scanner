def build() -> pd.DataFrame:
    rows = []
    for code, name, market, cap, bars in STOCKS:
        assert len(bars) == len(DATES), f"{name}: {len(bars)}행 (기대 {len(DATES)})"
        prev_close = None
        for d, (o, h, l, c, v) in zip(DATES, bars):          # 최신순
            rows.append({"date": d, "code": code, "name": name, "market": market,
                         "open": o, "high": h, "low": l, "close": c,
                         "chg": 0.0, "volume": v, "value": int(c) * int(v), "mktcap": cap})
    df = pd.DataFrame(rows).sort_values(["code", "date"]).reset_index(drop=True)
    df["chg"] = df.groupby("code")["close"].pct_change().fillna(0) * 100
    return df


def regime_from_index(name, closes):
    """지수 종가(최신순)로 국면 판정 — 실제 엔진의 시총합 지수 대신 실지수 사용."""
    s = pd.Series(closes[::-1])
    ma20 = s.rolling(20).mean().iloc[-1]
    ma60 = s.rolling(min(60, len(s))).mean().iloc[-1]
    last, prev = s.iloc[-1], s.iloc[-2]
    lo, hi = s.min(), s.max()
    if last < ma60:
        st, act = "위험", "신규 진입 중단 · 현금 비중 확대"
    elif last < ma20:
        st, act = "주의", "신규 1종목까지만 · 비중 절반"
    elif ma20 > ma60:
        st, act = "정상", "기준 충족 시 정상 진입"
    else:
        st, act = "혼조", "기준 충족 종목만 소량"
    pos = (last - lo) / (hi - lo) if hi > lo else 0.5
    if pos > 0.90 and st in ("정상", "혼조"):
        st, act = st + "(과열구간)", "분할 진입 · 목표 도달 시 기계적 익절"
    return {"market": name, "state": st, "action": act,
            "day_chg": round(float(last / prev - 1) * 100, 2),
            "pos_pct": round(float(pos) * 100, 1),
            "vs_ma20": round(float(last / ma20 - 1) * 100, 2),
            "vs_ma60": round(float(last / ma60 - 1) * 100, 2)}


